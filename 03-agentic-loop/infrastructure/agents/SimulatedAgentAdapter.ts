import type {
  AgentExecutionRequest,
  AgentExecutionResult,
  AgentOutcomeValue,
} from "../../core/domain/outbound/AgentGateway.port.js";
import {
  AGENT_ARTIFACT_KIND,
  AGENT_OUTCOME,
} from "../../core/domain/outbound/AgentGateway.port.js";
import type { AgentAdapter } from "./AgentGatewayRouter.js";

export class SimulatedAgentAdapter implements AgentAdapter {
  readonly provider: string;
  private readonly outcome: AgentOutcomeValue;
  private readonly delayMs: number;

  constructor(provider: string, outcome: AgentOutcomeValue, delayMs = 150) {
    this.provider = provider;
    this.outcome = outcome;
    this.delayMs = delayMs;
  }

  async execute(request: AgentExecutionRequest): Promise<AgentExecutionResult> {
    if (this.delayMs > 0) {
      await new Promise((resolve) => setTimeout(resolve, this.delayMs));
    }

    return {
      outcome: this.outcome,
      summary: this.summary(request),
      artifacts: [
        {
          kind: AGENT_ARTIFACT_KIND.PATCH,
          uri: `patch://${request.taskId}`,
          description: "Simulated patch generated by the CLI adapter",
        },
      ],
      usage: { inputTokens: 1200, outputTokens: 800, costUsd: 0.02 },
      raw: {
        provider: this.provider,
        agentId: request.agent.agentId,
        model: request.agent.model,
        instructions: request.instructions,
      },
    };
  }

  private summary(request: AgentExecutionRequest): string {
    switch (this.outcome) {
      case AGENT_OUTCOME.SUCCESS:
        return `Simulated success for task ${request.taskId}`;
      case AGENT_OUTCOME.FAILURE:
        return `Simulated failure for task ${request.taskId}`;
      case AGENT_OUTCOME.BLOCKED:
        return `Simulated blocker for task ${request.taskId}`;
    }
  }
}
